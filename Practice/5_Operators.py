# Program that takes two numbers and print their sum , multiply, difference and the num1 is greater than num2 

num1 = int(input("Enter the number:"))
num2 = int(input("Enter the second number:"))

sum = num1 + num2
product = num1 * num2
difference = num1 - num2 

print(f"Total of {num1} and {num2} is {sum}")
print(f"Product of {num1} and {num2} is {product}")
print(f"Difference of {num1} and {num2} is {difference}")